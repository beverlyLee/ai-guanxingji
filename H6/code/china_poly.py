def in_china(la, lo):
    ok = np.isfinite(la) & np.isfinite(lo) & (np.abs(la) <= 90) & (np.abs(lo) <= 180)
    res = np.zeros(len(la), dtype=bool)
    pts = np.column_stack([np.where(ok, lo, 0.0), np.where(ok, la, 0.0)])
    for p in CN_PATHS:
        res |= p.contains_points(pts)
    return res & ok
